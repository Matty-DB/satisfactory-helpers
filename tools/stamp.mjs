// Adds content hashes to the CSS and JS URLs in index.html so browsers never mix old and new files.
// Usage: node tools/stamp.mjs          rewrite index.html
//        node tools/stamp.mjs --check  exit 1 if index.html is out of date
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const hash = (rel) => createHash('sha1').update(readFileSync(join(ROOT, rel))).digest('hex').slice(0, 8);

export function stamped(html) {
  const scripts = readdirSync(join(ROOT, 'js')).filter((f) => f.endsWith('.js')).sort();
  // The import map rewrites every module import (including ones inside other modules) to a hashed URL.
  const map = { imports: Object.fromEntries(scripts.map((f) => [`./js/${f}`, `./js/${f}?v=${hash(`js/${f}`)}`])) };
  const block = `<!-- stamp:start (generated by tools/stamp.mjs) -->
  <link rel="stylesheet" href="css/styles.css?v=${hash('css/styles.css')}">
  <script type="importmap">${JSON.stringify(map)}</script>
  <!-- stamp:end -->`;
  const re = /<!-- stamp:start[\s\S]*?stamp:end -->/;
  if (!re.test(html)) throw new Error('index.html has no stamp markers');
  return html
    .replace(re, block)
    .replace(/<script type="module" src="js\/app\.js[^"]*"><\/script>/, `<script type="module" src="js/app.js?v=${hash('js/app.js')}"></script>`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = join(ROOT, 'index.html');
  const html = readFileSync(file, 'utf8');
  const next = stamped(html);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('index.html is out of date: run `npm run stamp`'); process.exit(1); }
  } else {
    writeFileSync(file, next);
    console.log(next === html ? 'index.html already up to date' : 'index.html stamped');
  }
}
